def random_item():
    return random.choice(ITEMS)


def build_quest(template_list, **kwargs):
    template = random.choice(template_list)
    item = kwargs.get("item") or random_item()
    kwargs["item"] = item
    return template.format(**kwargs)


def drinking_quest():
    return build_quest(DRINKING_QUESTS)


def dining_out_quest():
    return build_quest(DINING_OUT_QUESTS)


def calendar_quest(event_name):
    return build_quest(CALENDAR_QUESTS, event=event_name)


def success_line():
    return random.choice(SUCCESS_LINES)


def slack_line():
    return random.choice(SLACK_LINES)
